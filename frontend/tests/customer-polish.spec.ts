import { test, expect } from '@playwright/test';

test('short desktop viewport keeps every catalog filter reachable and search focus surrounds its container', async ({ page }, info) => {
  await page.setViewportSize({ width: 1280, height: 600 });
  await page.route('**/api/v1/**', route => {
    const path = new URL(route.request().url()).pathname;
    if (path.includes('/auth/')) return route.fulfill({ status: 401, json: { code: 'UNAUTHORIZED', message: 'Signed out' } });
    if (path.endsWith('/categories')) return route.fulfill({ json: { items: Array.from({ length: 18 }, (_, i) => ({ id: '10000000-0000-4000-8000-' + String(i).padStart(12, '0'), name: 'Danh mục ' + i })), page: 1, size: 100, total: 18 } });
    return route.fulfill({ json: { items: [], page: 1, size: 20, total: 0 } });
  });
  await page.goto('/?q=ao');
  const filters = page.getByRole('complementary', { name: 'Bộ lọc sản phẩm' });
  const drawerTrigger = page.getByRole('button', { name: 'Bộ lọc', exact: true });
  await expect(drawerTrigger).toHaveCount(0);
  await expect(page.getByText('0 sản phẩm', { exact: true })).toHaveCount(1);
  await expect(page.getByText('0 kết quả', { exact: false })).toHaveCount(0);
  await expect(filters.getByRole('link', { name: 'Bắt đầu bán hàng' })).toHaveCount(0);
  await expect(filters.getByRole('button', { name: 'Danh mục 17', exact: true })).toBeAttached();
  await filters.getByLabel('Giá đến').focus();
  await expect(filters.getByLabel('Giá đến')).toBeInViewport();
  expect(await filters.evaluate(el => el.scrollTop)).toBeGreaterThan(0);
  await filters.getByRole('button', { name: 'Áp dụng', exact: true }).focus();
  await expect(filters.getByRole('button', { name: 'Áp dụng', exact: true })).toBeInViewport();
  const search = page.getByRole('searchbox', { name: 'Tìm kiếm toàn sàn' });
  await search.focus();
  expect(await search.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('none');
  expect(await search.evaluate(el => getComputedStyle(el.closest('form')!).outlineStyle)).toBe('solid');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('filters-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(filters).toBeHidden();
  await drawerTrigger.click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.setViewportSize({ width: 1024, height: 844 });
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(filters).toBeVisible();
  await expect(drawerTrigger).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await drawerTrigger.click();
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Áp dụng', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('filters-mobile.png') });
  await page.getByRole('dialog').getByRole('combobox').selectOption('10000000-0000-4000-8000-000000000017');
  await page.getByRole('dialog').getByLabel('Giá từ').fill('100');
  await page.getByRole('dialog').getByLabel('Giá đến').fill('500');
  await page.getByRole('dialog').getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect.poll(() => new URL(page.url()).searchParams.get('category')).toBe('10000000-0000-4000-8000-000000000017');
  await expect.poll(() => new URL(page.url()).searchParams.get('min')).toBe('100');
  await expect.poll(() => new URL(page.url()).searchParams.get('max')).toBe('500');
});
